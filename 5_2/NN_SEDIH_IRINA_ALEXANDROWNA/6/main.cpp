#include <iostream>
#include <cmath>

// Function
double f(double x) {
    return pow(x, 4) - 10 * pow(x, 2) + 0.5 * x + 8;
}

// Derivative: f'(x) = 4x^3 - 20x + 0.5
double grad(double x) {
    return 4 * pow(x, 3) - 20 * x + 0.5;
}

int main() {
    // Initial point
    double x = -3.0;

    // AdamW parameters
    double lr = 0.05;        // learning rate
    double beta1 = 0.9;
    double beta2 = 0.999;
    double eps = 1e-8;
    double weight_decay = 0.01;

    // Moments
    double m = 0.0;
    double v = 0.0;

    int iterations = 100;

    for (int t = 1; t <= iterations; ++t) {
        double g = grad(x);

        // Update biased moments
        m = beta1 * m + (1 - beta1) * g;
        v = beta2 * v + (1 - beta2) * g * g;

        // Bias correction
        double m_hat = m / (1 - pow(beta1, t));
        double v_hat = v / (1 - pow(beta2, t));

        // AdamW update (decoupled weight decay)
        x -= lr * (m_hat / (std::sqrt(v_hat) + eps) + weight_decay * x);

        std::cout << "Iter " << t
                  << " | x = " << x
                  << " | f(x) = " << f(x)
                  << std::endl;
    }

    std::cout << "\nFinal x: " << x << std::endl;
    std::cout << "Final f(x): " << f(x) << std::endl;

    return 0;
}
