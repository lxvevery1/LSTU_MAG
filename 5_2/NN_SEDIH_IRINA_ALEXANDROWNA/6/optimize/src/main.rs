fn function(x: f64) -> f64 {
    x.powi(4) - 10.0 * x.powi(2) + 0.5 * x + 8.0
}

fn derivative(x: f64) -> f64 {
    4.0 * x.powi(3) - 20.0 * x + 0.5
}

fn AdamW(
    func: fn(f64) -> f64,
    grad: fn(f64) -> f64,
    start_point: f64,
    learning_rate: f64,
    beta1: f64,
    beta2: f64,
    epsilon: f64,
    weight_decay: f64,
    iterations: usize,
) -> Vec<f64> {
    let mut x = start_point;
    let mut m = 0.0;
    let mut v = 0.0;
    let mut trajectory = Vec::new();

    for t in 1..=iterations {
        let g = grad(x);
        m = beta1 * m + (1.0 - beta1) * g;
        v = beta2 * v + (1.0 - beta2) * g.powi(2);

        let m_hat = m / (1.0 - beta1.powi(t as i32));
        let v_hat = v / (1.0 - beta2.powi(t as i32));

        x -= learning_rate * (m_hat / (v_hat.sqrt() + epsilon) + weight_decay * x);

        if t % 5 == 0 || t == iterations {
            trajectory.push(x);
        }
    }

    // print x
    println!("Final x: {}", x);
    println!("Final f(x): {}", func(x));

    trajectory
}

const START_POINT: f64 = -3.0;

fn main() {
    AdamW(
        function,
        derivative,
        START_POINT,
        0.05,
        0.9,
        0.999,
        1e-8,
        0.01,
        100,
    );
}
